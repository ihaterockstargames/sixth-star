const MIB: usize = 1 << 20;

/// Whether we run under Wine (its ntdll exports `wine_get_version`).
pub(crate) fn on_wine() -> bool {
    static WINE: LazyLock<bool> = LazyLock::new(|| {
        use windows_sys::Win32::System::LibraryLoader::{GetModuleHandleA, GetProcAddress};
        // SAFETY: plain lookups in ntdll, always loaded.
        unsafe {
            let ntdll = GetModuleHandleA(c"ntdll.dll".as_ptr().cast());
            !ntdll.is_null() && GetProcAddress(ntdll, c"wine_get_version".as_ptr().cast()).is_some()
        }
    });
    *WINE
}

/// Standard memory the title has handed to the system.
static TRANSFERRED: AtomicUsize = AtomicUsize::new(0);

// Console additions to the host's flags.
/// 2 MiB pages; the host reads this bit as large pages, which need a
/// privilege.
const PAGES_2M: u32 = 0x2000_0000;
/// With `PAGES_2M`: 64 KiB pages; the host reads it as AWE memory.
const PAGES_64K_BIT: u32 = 0x40_0000;
const PAGES_64K: u32 = PAGES_2M | PAGES_64K_BIT;
/// The host's protection constants and `PAGE_GUARD`. Above them the console
/// adds GPU access bits (0x800-0x40000). Write-combining and uncached are
/// dropped too: our GPU side reads this memory through the CPU.
const HOST_PROTECTION: u32 = 0x1ff;
/// XMem flags of memory both processors reach: all of ours.
const GRAPHICS: u64 = 3;
/// XMem flag bit of 32-bit graphics memory.
const ADDRESS_32BIT: u64 = 4;
/// The host's write watching (not in windows-sys' memory module).
const MEM_WRITE_WATCH: u32 = 0x20_0000;

/// The addresses XMem `flags` allow, first and last: the low 4 GiB for
/// 32-bit memory; else from 4 GiB (kept for 32-bit requests, which the
/// title's big pools would otherwise crowd out) up to 46 down to 40 bits
/// from the field at bit 12, or 40 bits without one: the console keeps
/// title memory there, and its ray-tracing structures must be (
/// the title's BVH builder refuses one above; the title asks for its GPU heap
/// with no field). Decision 0001.
///
/// Capped at the raw-address directory's end
/// ([`victory_gpu::addr::DIRECTORY_END`], 128 GiB − 64 KiB): shaders reach
/// title memory by address only below it, and the console's limit (40
/// bits) is kept by any range inside it.
fn address_range(flags: u64) -> (usize, usize) {
    let (lowest, highest) = console_range(flags);
    if flags & ADDRESS_32BIT != 0 {
        return (lowest, highest);
    }
    let capped = (highest as u64).min(victory_gpu::addr::DIRECTORY_END - 1);
    (lowest, capped as usize)
}

/// The console's own range for `flags`, uncapped (what a reservation the
/// capped range cannot hold falls back to, see [`XMemVirtualAlloc`]).
fn console_range(flags: u64) -> (usize, usize) {
    let bits = match (flags & ADDRESS_32BIT, flags >> 12 & 7) {
        (0, 0) => 40,
        (0, field) => 47 - field,
        _ => return (0, u32::MAX as usize),
    };
    (1 << 32, ((1u64 << bits) - 1) as usize)
}

/// `VirtualAlloc`'s top-down flag: the reservation goes as high as the
/// range allows (with the cap, just below the directory's end: still
/// reachable). Kept as the title asks.
const MEM_TOP_DOWN: u32 = 0x10_0000;


/// What the title asks memory for, by the console's own description of it
/// (B-05): the protection bits above the host's (write-combine, uncached,
/// GPU access), the page-size and commit bits, and the XMem flags; or an
/// `XMemAlloc` attribute word. Counted per distinct key, with the bytes
/// asked; a key seen for the first time is logged, so a run shows which
/// kinds of memory the title uses and how much of each.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum MemoryClass {
    Virtual { protect: u32, kind: u32, flags: u64 },
    Alloc { attributes: u64 },
}

static CENSUS: Mutex<BTreeMap<MemoryClass, (u64, u64)>> = Mutex::new(BTreeMap::new());
/// Kinds kept apart at most; more are counted together.
const CENSUS_KINDS: usize = 256;
/// Requests not counted by kind: the census was busy (it never makes the
/// title's allocator wait), or past [`CENSUS_KINDS`].
static CENSUS_UNSORTED: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

fn note_class(class: MemoryClass, bytes: usize) {
    use std::sync::atomic::Ordering::Relaxed;
    let first = {
        let Ok(mut census) = CENSUS.try_lock() else {
            CENSUS_UNSORTED.fetch_add(1, Relaxed);
            return;
        };
        if !census.contains_key(&class) && census.len() >= CENSUS_KINDS {
            CENSUS_UNSORTED.fetch_add(1, Relaxed);
            return;
        }
        let entry = census.entry(class).or_insert((0, 0));
        entry.0 += 1;
        entry.1 += bytes as u64;
        entry.0 == 1
    };
    if first {
        tracing::info!(?class, bytes, "title memory: first request of this kind");
    }
}

/// Every kind of memory the title asked for so far: requests and bytes.
pub fn memory_census() -> Vec<(MemoryClass, u64, u64)> {
    let census = CENSUS.lock().unwrap_or_else(|e| e.into_inner());
    census.iter().map(|(&c, &(n, b))| (c, n, b)).collect()
}

/// The census as one line for the periodic report: kinds, and the five
/// with the most bytes asked.
pub fn census_line() -> String {
    let mut all = memory_census();
    all.sort_by_key(|k| std::cmp::Reverse(k.2));
    let top: Vec<String> = all
        .iter()
        .take(5)
        .map(|(c, n, b)| format!("{c:?}: {n}x {} MB", b >> 20))
        .collect();
    format!(
        "memory census: {} kinds, {} requests unsorted; most bytes: {}",
        all.len(),
        CENSUS_UNSORTED.load(std::sync::atomic::Ordering::Relaxed),
        top.join(", ")
    )
}

pub extern "system" fn XMemVirtualAlloc(
    base: *mut c_void,
    size: usize,
    kind: u32,
    flags: u64,
    protect: u32,
) -> *mut c_void {
    let console_protect = protect;
    note_class(
        MemoryClass::Virtual {
            protect: protect & !HOST_PROTECTION,
            kind: kind & (PAGES_2M | PAGES_64K_BIT | MEM_COMMIT | MEM_RESERVE | MEM_TOP_DOWN),
            flags,
        },
        size,
    );
    let (lowest, highest) = address_range(flags);
    let mut requirements = MEM_ADDRESS_REQUIREMENTS {
        LowestStartingAddress: lowest as *mut c_void,
        HighestEndingAddress: highest as *mut c_void,
        Alignment: if kind & (PAGES_2M | PAGES_64K_BIT) == PAGES_2M {
            2 * MIB
        } else {
            0
        },
    };
    let mut protect = match protect & HOST_PROTECTION {
        0 => PAGE_NOACCESS,
        p => p,
    };
    // A reservation of 64 KiB pages takes physical pages later
    // (`XMemMapPhysicalPages`); on the host only a placeholder can.
    // shortcut: committing part of such a reservation later would fail
    // (the title's 23 calls never do); replace that part of the
    // placeholder then.
    let placeholder = kind & PAGES_64K == PAGES_64K && kind & MEM_COMMIT == 0;
    if placeholder {
        if kind & MEM_REPLACE_PLACEHOLDER != 0 {
            // Part of a placeholder the title split: it stays one.
            return base;
        }
        protect = PAGE_NOACCESS;
    }
    let mut kind = kind & !(PAGES_2M | PAGES_64K_BIT);
    if placeholder {
        kind |= MEM_RESERVE | MEM_RESERVE_PLACEHOLDER;
    }
    let mut parameter = MEM_EXTENDED_PARAMETER::default();
    parameter.Anonymous1._bitfield = MemExtendedParameterAddressRequirements as u64;
    parameter.Anonymous2.Pointer = (&raw mut requirements).cast();
    // Address requirements apply to reservations at an address of our choice.
    let constrained = base.is_null();
    if constrained {
        kind |= MEM_RESERVE;
        // The GPU side copies only the pages the title wrote since its last
        // copy (`victory_gpu`, decision 0007); placeholders cannot be
        // watched (their physical-page views are copied whole).
        if kind & MEM_RESERVE_PLACEHOLDER == 0 {
            kind |= MEM_WRITE_WATCH;
        }
    }
    // SAFETY: the title's own arguments, cleaned of console bits; the
    // parameter points at `requirements`, which outlives the call.
    let mut at = unsafe {
        VirtualAlloc2(
            GetCurrentProcess(),
            base,
            size,
            kind,
            protect,
            if constrained {
                &mut parameter
            } else {
                std::ptr::null_mut()
            },
            constrained.into(),
        )
    };
    // The cap must not fail the title: a reservation the capped range
    // cannot hold is made where the console would put it, counted, and
    // logged (shaders reaching it by address read zeros; diagnostic first).
    if at.is_null() && constrained && flags & ADDRESS_32BIT == 0 {
        let (_, console_highest) = console_range(flags);
        if console_highest > highest {
            // Through the parameter's pointer, which the call reads.
            // SAFETY: the union holds the pointer set above, to
            // `requirements`, alive and ours; then the call as above, with
            // the console's own range.
            unsafe {
                let wanted = parameter.Anonymous2.Pointer.cast::<MEM_ADDRESS_REQUIREMENTS>();
                (*wanted).HighestEndingAddress = console_highest as *mut c_void;
            }
            at = unsafe { VirtualAlloc2(GetCurrentProcess(), base, size, kind, protect, &mut parameter, 1) };
            if !at.is_null() {
                let n = victory_gpu::addr::note_capped_fallback();
                if n < 32 {
                    tracing::warn!(
                        size,
                        flags = format_args!("{flags:#x}"),
                        at = format_args!("{at:p}"),
                        "XMemVirtualAlloc: no room below the raw-address directory's end; reserved in the console's range"
                    );
                }
            }
        }
    }
    if base.is_null() {
        tracing::debug!(
            size,
            kind = format_args!("{kind:#x}"),
            flags = format_args!("{flags:#x}"),
            at = format_args!("{at:p}"),
            "XMemVirtualAlloc"
        );
    }
    if !at.is_null() {
        // All of it is GPU-reachable here (see `XMemVirtualQuery`).
        victory_gpu::addr::note_title_range(at as u64, size as u64, "XMemVirtualAlloc");
        // The console's kind of this memory, for the Gen 2 census.
        victory_gpu::title_memory_kind(at as usize, size, console_protect);
    }
    at
}

/// `MEMORY_BASIC_INFORMATION` (the console's first 0x30 bytes are the
/// same), then the XMem flags and tag.
#[repr(C)]
pub struct BasicInformation {
    host: MEMORY_BASIC_INFORMATION,
    flags: u64,
    tag_code: u32,
    tag: [u8; 4],
}

// shortcut: every committed page reports graphics memory and no tag, since
// all of it is GPU-reachable here (the title's BVH builder, the
// only caller, wants graphics memory); remember the flags of
// `XMemVirtualAlloc` regions if a title tells CPU-only memory apart.
pub extern "system" fn XMemVirtualQuery(
    process: HANDLE,
    address: *const c_void,
    out: *mut BasicInformation,
) -> BOOL {
    let size = size_of::<MEMORY_BASIC_INFORMATION>();
    // SAFETY: the title passes room for the whole structure; the host
    // fails on a null one.
    unsafe {
        if VirtualQueryEx(process, address, out.cast(), size) == 0 {
            return 0;
        }
        let info = &mut *out;
        info.flags = if info.host.State == MEM_COMMIT {
            GRAPHICS
        } else {
            0
        };
        info.tag_code = 0;
        info.tag = [0; 4];
    }
    1
}

// `XMemAlloc` attributes: alignment as log2 (5 bits at 24, 4 bytes and up
// from 2), then the memory type, then bit 33: a 32-bit address.
const ALIGNMENT_SHIFT: u64 = 24;
const ALLOC_32BIT: u64 = 1 << 33;
/// Our block header: the block's size and alignment, just below the
/// pointer handed out.
const HEADER: usize = 2 * size_of::<usize>();

/// With `VICTORY_WATCHED_ALLOC=1`, blocks of [`XMemAllocDefault`] of at
/// least this size, at an alignment of at most this, are a write-watched
/// reservation of their own instead of host heap memory: the GPU side then
/// copies only the pages the title wrote since its last copy (decision
/// 0007), where heap memory is copied whole at every refresh (a committed
/// buffer's memory comes from here unless the title hooks the allocator).
///
/// Off by default, on the stand-in title's measurements (2026-11-28, 8
/// buffers of 3 MB, texture copies from buffers): with 10% of each buffer
/// rewritten a frame, CPU preparing 2.5 -> 0.3 ms and 24.6 -> 2.6 MB
/// copied; with whole buffers rewritten, CPU preparing 2.6 -> 3.2 ms (the
/// write watch asked 13 times a frame instead of 5) and the title's own
/// frame 10.8 -> 15.6 ms (its writes after each reset of the watch cost
/// more). A default needs the runtime to stop asking for buffers it keeps
/// finding wholly written.
const WATCHED_MIN: usize = 64 << 10;

/// The blocks [`XMemAllocDefault`] reserved on their own ([`WATCHED_MIN`]).
static WATCHED: LazyLock<Mutex<HashSet<usize>>> = LazyLock::new(Default::default);

fn watched() -> MutexGuard<'static, HashSet<usize>> {
    WATCHED.lock().unwrap_or_else(|e| e.into_inner())
}

/// Whether large default blocks are write-watched reservations
/// ([`WATCHED_MIN`]): only with `VICTORY_WATCHED_ALLOC=1`.
fn watched_alloc() -> bool {
    static ON: LazyLock<bool> =
        LazyLock::new(|| watched_switch(std::env::var_os("VICTORY_WATCHED_ALLOC").as_deref()));
    *ON
}

/// `VICTORY_WATCHED_ALLOC`'s value: only `1` turns it on.
fn watched_switch(value: Option<&std::ffi::OsStr>) -> bool {
    value.and_then(|v| v.to_str()) == Some("1")
}

/// A write-watched reservation for a default block, if it is one
/// ([`WATCHED_MIN`]); null if not, or if the host has no room.
fn watched_block(size: usize, attributes: u64) -> *mut c_void {
    let align = 1usize << (attributes >> ALIGNMENT_SHIFT & 0x1f);
    if size < WATCHED_MIN || align > WATCHED_MIN {
        return std::ptr::null_mut();
    }
    // SAFETY: a plain reservation of our own, at an address of the host's
    // choice (64 KiB aligned); its pages start zeroed.
    let at = unsafe {
        VirtualAlloc(
            std::ptr::null(),
            size,
            MEM_RESERVE | MEM_COMMIT | MEM_WRITE_WATCH,
            PAGE_READWRITE,
        )
    };
    if !at.is_null() {
        watched().insert(at as usize);
    }
    at
}

fn layout(size: usize, attributes: u64) -> Option<Layout> {
    // An alignment of at least 16 leaves room for the header.
    let align = 1usize << (attributes >> ALIGNMENT_SHIFT & 0x1f).max(4);
    Layout::from_size_align(size.checked_add(align)?, align).ok()
}

type AllocRoutine = extern "system" fn(usize, u64) -> *mut c_void;
type FreeRoutine = extern "system" fn(*mut c_void, u64);

/// The allocation and free routines the title's exe exports as
/// `__XMemAllocationHooks__` (the title does): `XMemAlloc` and
/// `XMemFree` call them, for the title's own calls and its middleware's;
/// the `…Default` exports do not.
fn hooks() -> [usize; 2] {
    static AT: std::sync::OnceLock<usize> = std::sync::OnceLock::new();
    let at = match AT.get() {
        Some(&at) => at,
        // Looked up once the title is mapped, which is before it runs.
        None => match crate::runtime::main_image() {
            Some(base) => *AT.get_or_init(|| {
                use windows_sys::Win32::System::LibraryLoader::GetProcAddress;
                // SAFETY: a mapped image and a NUL-terminated name.
                let at = unsafe {
                    GetProcAddress(base as _, c"__XMemAllocationHooks__".as_ptr().cast())
                }
                .map_or(0, |f| f as usize);
                tracing::info!(found = at != 0, "xmem allocation hooks");
                at
            }),
            None => 0,
        },
    };
    if at == 0 {
        return [0; 2];
    }
    // SAFETY: the export is two routine pointers.
    unsafe { (at as *const [usize; 2]).read() }
}

/// The title's general allocator, for middleware too: its hook if it has
/// one, else [`XMemAllocDefault`].
pub extern "system" fn XMemAlloc(size: usize, attributes: u64) -> *mut c_void {
    note_class(MemoryClass::Alloc { attributes }, size);
    match hooks()[0] {
        0 => XMemAllocDefault(size, attributes),
        hook => {
            // SAFETY: the title's own routine of this type.
            let alloc: AllocRoutine = unsafe { std::mem::transmute(hook) };
            alloc(size, attributes)
        }
    }
}

/// See [`XMemAlloc`].
pub extern "system" fn XMemFree(address: *mut c_void, attributes: u64) {
    match hooks()[1] {
        0 => XMemFreeDefault(address, attributes),
        hook => {
            // SAFETY: the title's own routine of this type.
            let free: FreeRoutine = unsafe { std::mem::transmute(hook) };
            free(address, attributes)
        }
    }
}

/// The system allocator behind [`XMemAlloc`].
pub extern "system" fn XMemAllocDefault(size: usize, attributes: u64) -> *mut c_void {
    if attributes & ALLOC_32BIT != 0 {
        return XMemVirtualAlloc(
            std::ptr::null_mut(),
            size,
            MEM_RESERVE | MEM_COMMIT,
            GRAPHICS | ADDRESS_32BIT,
            PAGE_READWRITE,
        );
    }
    if watched_alloc() {
        let block = watched_block(size, attributes);
        if !block.is_null() {
            return block;
        }
    }
    let Some(layout) = layout(size, attributes) else {
        return std::ptr::null_mut();
    };
    // shortcut: the host heap's addresses lie above 2^40, unlike the
    // console's; nothing seen builds ray-tracing structures in this memory
    // (the title uses its GPU heap). Sub-allocate from a
    // reservation below 2^40 if one does.
    // SAFETY: the layout has a non-zero size.
    let block = unsafe { alloc(layout) };
    if block.is_null() {
        return block.cast();
    }
    // SAFETY: the block holds the alignment (at least the header) and then
    // `size` bytes.
    unsafe {
        let user = block.add(layout.align());
        user.sub(HEADER)
            .cast::<[usize; 2]>()
            .write([layout.size(), layout.align()]);
        user.cast()
    }
}

/// Frees what [`XMemAllocDefault`] returned, given the same attributes.
pub extern "system" fn XMemFreeDefault(address: *mut c_void, attributes: u64) {
    if address.is_null() {
        return;
    }
    if watched().remove(&(address as usize)) {
        // SAFETY: a whole reservation of `watched_block`, freed once.
        unsafe { VirtualFree(address, 0, MEM_RELEASE) };
        return;
    }
    // SAFETY: the address came from `XMemAlloc` with these attributes: a
    // whole reservation, or a header-prefixed block.
    unsafe {
        if attributes & ALLOC_32BIT != 0 {
            VirtualFree(address, 0, MEM_RELEASE);
            return;
        }
        let user = address.cast::<u8>();
        let [size, align] = user.sub(HEADER).cast::<[usize; 2]>().read();
        dealloc(
            user.sub(align),
            Layout::from_size_align_unchecked(size, align),
        );
    }
}

